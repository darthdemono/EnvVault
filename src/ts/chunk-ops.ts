export function exportNginx(project: Project): string {
  const chunks = activeChunks(project);
  const upstreams = chunks.filter((c) => c.chunk_type === 'nginx_upstream');
  const servers = chunks.filter((c) => c.chunk_type === 'nginx_server');
  const locations = chunks.filter((c) => c.chunk_type === 'nginx_location');
  const lines: string[] = ['# Generated by EnvVault', ''];

  // Resolve, as every other exporter does. This one interpolated `f.value`
  // raw, so an `ssl_certificate ${TLS}` written by the starter template reached
  // nginx as the literal text `${TLS}` and the server refused to start — while
  // copying the same chunk from the card resolved it correctly, so the two
  // disagreed about what the config said.
  const rv = (v: string) => resolveFieldRef(v ?? '', true).resolved ?? v ?? '';

  for (const u of upstreams) {
    lines.push(`upstream ${u.name} {`);
    for (const f of u.fields) {
      if (!f.value) continue;
      if (f.key === 'server') {
        for (const v of rv(f.value)
          .split(/[\n,]+/)
          .map((s) => s.trim())
          .filter(Boolean))
          lines.push(`    server ${v};`);
      } else {
        lines.push(`    ${f.key} ${rv(f.value)};`);
      }
    }
    lines.push('}', '');
  }

  for (const s of servers) {
    lines.push('server {');
    for (const f of s.fields) {
      if (f.value) lines.push(`    ${f.key} ${rv(f.value)};`);
    }
    if (locations.length) {
      lines.push('');
      for (const loc of locations) {
        const path = loc.fields.find((f) => f.key === 'path')?.value || '/';
        lines.push(`    location ${path} {`);
        for (const f of loc.fields) {
          if (f.key !== 'path' && f.value) lines.push(`        ${f.key} ${rv(f.value)};`);
        }
        lines.push('    }');
      }
    }
    lines.push('}', '');
  }
  return lines.join('\n');
}

/**
 * Base64 of a string's UTF-8 bytes, as Kubernetes `Secret.data` requires.
 *
 * `btoa` operates on Latin-1 code units, which broke this two ways: any
 * character above U+00FF (an emoji, CJK, anything outside Latin-1) threw
 * `InvalidCharacterError` and took the whole export down, and a character in
 * U+0080–U+00FF — `é`, `£`, `ü` — encoded its Latin-1 byte instead of its UTF-8
 * bytes, so the cluster silently decoded a *different* secret than the one
 * stored. The quiet corruption is the worse of the two.
 */
function b64Utf8(s: string): string {
  const bytes = new TextEncoder().encode(s);
  const CHUNK = 0x8000;
  let bin = '';
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode(...bytes.subarray(i, i + CHUNK));
  }
  return btoa(bin);
}

export function exportK8s(project: Project): string {
  const manifests: string[] = [];
  for (const chunk of activeChunks(project)) {
    const name = chunk.fields.find((f) => f.key === 'name')?.value || chunk.name;
    const ns = chunk.fields.find((f) => f.key === 'namespace')?.value || 'default';
    if (chunk.chunk_type === 'k8s_deployment') {
      const image = chunk.fields.find((f) => f.key === 'image')?.value || 'nginx:latest';
      const replicas = chunk.fields.find((f) => f.key === 'replicas')?.value || '1';
      const port = chunk.fields.find((f) => f.key === 'containerPort')?.value || '80';
      const envFields = chunk.fields.filter(
        (f) => f.field_type === 'env_var' || f.field_type === 'secret',
      );
      const envBlock = envFields.length
        ? '\n        env:' +
          envFields
            .map(
              (f) => `\n          - name: ${f.key}\n            value: ${JSON.stringify(f.value)}`,
            )
            .join('')
        : '';
      manifests.push(
        `apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: ${name}\n  namespace: ${ns}\nspec:\n  replicas: ${replicas}\n  selector:\n    matchLabels:\n      app: ${name}\n  template:\n    metadata:\n      labels:\n        app: ${name}\n    spec:\n      containers:\n        - name: ${name}\n          image: ${image}\n          ports:\n            - containerPort: ${port}${envBlock}`,
      );
    } else if (chunk.chunk_type === 'k8s_service') {
      const port = chunk.fields.find((f) => f.key === 'port')?.value || '80';
      const targetPort = chunk.fields.find((f) => f.key === 'targetPort')?.value || '80';
      const type = chunk.fields.find((f) => f.key === 'type')?.value || 'ClusterIP';
      manifests.push(
        `apiVersion: v1\nkind: Service\nmetadata:\n  name: ${name}\n  namespace: ${ns}\nspec:\n  selector:\n    app: ${name}\n  type: ${type}\n  ports:\n    - port: ${port}\n      targetPort: ${targetPort}`,
      );
    } else if (chunk.chunk_type === 'k8s_configmap') {
      const dataFields = chunk.fields.filter((f) => f.key !== 'name' && f.key !== 'namespace');
      manifests.push(
        `apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: ${name}\n  namespace: ${ns}\ndata:\n${dataFields.map((f) => `  ${f.key}: ${JSON.stringify(f.value)}`).join('\n')}`,
      );
    } else if (chunk.chunk_type === 'k8s_secret') {
      const dataFields = chunk.fields.filter((f) => f.key !== 'name' && f.key !== 'namespace');
      // Resolve references before encoding — a field holding `${DB_PASSWORD}`
      // was base64'd literally, shipping the placeholder text to the cluster as
      // if it were the secret.
      manifests.push(
        `apiVersion: v1\nkind: Secret\nmetadata:\n  name: ${name}\n  namespace: ${ns}\ntype: Opaque\ndata:\n${dataFields.map((f) => `  ${f.key}: ${b64Utf8(resolveFieldRef(f.value ?? '', true).resolved ?? f.value ?? '')}`).join('\n')}`,
      );
    } else if (chunk.chunk_type === 'k8s_ingress') {
      const host = chunk.fields.find((f) => f.key === 'host')?.value || 'example.com';
      const svcName = chunk.fields.find((f) => f.key === 'serviceName')?.value || name;
      const svcPort = chunk.fields.find((f) => f.key === 'servicePort')?.value || '80';
      manifests.push(
        `apiVersion: networking.k8s.io/v1\nkind: Ingress\nmetadata:\n  name: ${name}\n  namespace: ${ns}\nspec:\n  rules:\n    - host: ${host}\n      http:\n        paths:\n          - path: /\n            pathType: Prefix\n            backend:\n              service:\n                name: ${svcName}\n                port:\n                  number: ${svcPort}`,
      );
    }
  }
  return manifests.join('\n---\n');
}

export function exportSshConfig(project: Project): string {
  const lines: string[] = ['# Generated by EnvVault', ''];
  for (const chunk of activeChunks(project)) {
    if (chunk.chunk_type !== 'ssh_host') continue;
    lines.push(`Host ${chunk.name}`);
    for (const f of chunk.fields) {
      if (f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function exportTraefik(project: Project): string {
  const chunks = activeChunks(project);
  const routers = chunks.filter((c) => c.chunk_type === 'traefik_router');
  const services = chunks.filter((c) => c.chunk_type === 'traefik_service');
  const middlewares = chunks.filter((c) => c.chunk_type === 'traefik_middleware');
  const lines: string[] = ['# Generated by EnvVault', 'http:'];

  if (routers.length) {
    lines.push('  routers:');
    for (const r of routers) {
      lines.push(`    ${r.name}:`);
      for (const f of r.fields) {
        if (!f.value) continue;
        if (f.field_type === 'list') {
          lines.push(`      ${f.key}:`);
          for (const item of xv(f.value)
            .split(/[\n,]+/)
            .map((s) => s.trim())
            .filter(Boolean))
            lines.push(`        - ${item}`);
        } else {
          lines.push(`      ${f.key}: ${JSON.stringify(xv(f.value))}`);
        }
      }
    }
  }
  if (services.length) {
    lines.push('  services:');
    for (const s of services) {
      const url = xv(s.fields.find((f) => f.key === 'url')?.value);
      const passHost = xv(s.fields.find((f) => f.key === 'passHostHeader')?.value) || 'true';
      lines.push(`    ${s.name}:`, `      loadBalancer:`, `        passHostHeader: ${passHost}`);
      if (url) {
        lines.push(`        servers:`, `          - url: ${JSON.stringify(url)}`);
      }
    }
  }
  if (middlewares.length) {
    lines.push('  middlewares:');
    for (const m of middlewares) {
      const type = xv(m.fields.find((f) => f.key === 'type')?.value);
      lines.push(`    ${m.name}:`);
      if (type) {
        lines.push(`      ${type}:`);
        for (const f of m.fields) {
          if (f.key !== 'type' && f.value) lines.push(`        ${f.key}: ${xv(f.value)}`);
        }
      }
    }
  }
  return lines.join('\n');
}

export function pickFileText(
  accept: string,
  cb: (text: string, name: string) => void | Promise<void>,
): void {
  const inp = document.createElement('input');
  inp.type = 'file';
  inp.accept = accept;
  document.body.appendChild(inp);
  let done = false;
  const cleanup = () => {
    if (done) return;
    done = true;
    if (document.body.contains(inp)) document.body.removeChild(inp);
  };
  inp.addEventListener(
    'change',
    function () {
      const file = (this as HTMLInputElement).files?.[0];
      if (!file) {
        cleanup();
        return;
      }
      const reader = new FileReader();
      reader.onload = (ev) => cb(ev.target!.result as string, file.name);
      reader.readAsText(file);
      cleanup();
    },
    { once: true },
  );
  inp.addEventListener('cancel', cleanup, { once: true });
  inp.click();
  setTimeout(() => window.addEventListener('focus', cleanup, { once: true }), 300);
}
