/** Canonical names for well-known field suffixes used in env var naming conventions. */
/**
 * Reference alias → the **vault-entry JSON field name** it resolves to.
 *
 * The values are the JSON names (`api_key`, not `key`) so this table and
 * `canonical_field` in `envv-cli/src/refs.rs` are the same table written twice
 * rather than two tables that happen to agree. Pinned from both sides by
 * `tests/fixtures/parity/field-aliases.json`.
 */
const FIELD_ALIASES: Readonly<Record<string, string>> = {
  APIKEY: 'api_key',
  API_KEY: 'api_key',
  KEY: 'api_key',
  TOKEN: 'api_key',
  ACCESS_TOKEN: 'api_key',
  BEARER: 'api_key',
  SECRET_KEY: 'api_key',
  PASSWORD: 'api_key',
  PASS: 'api_key',
  PWD: 'api_key',
  // ↑ a password entry stores its secret in api_key, so ${name/password} resolves there too
  SECRET: 'api_secret',
  API_SECRET: 'api_secret',
  CLIENT_SECRET: 'api_secret',
  SHARED_SECRET: 'api_secret',
  USERNAME: 'username',
  USER: 'username',
  LOGIN: 'username',
  USER_NAME: 'username',
  URL: 'api_url',
  URI: 'api_url',
  ENDPOINT: 'api_url',
  API_URL: 'api_url',
  BASE_URL: 'api_url',
  EMAIL: 'email',
  MAIL: 'email',
  KEY_ID: 'key_id',
  KEYID: 'key_id',
  KID: 'key_id',
  // The public half of an OAuth pair: `key_id`, then an `extra_vars` entry
  // keyed `ID`, which is where a client id lives in vaults written today.
  // Before this arm existed the app left `${Spotify/ID}` as literal text while
  // the CLI resolved it to the entry's UUID — the same reference, two wrong
  // answers, neither of them reported.
  ID: 'key_id',
  CLIENT_ID: 'key_id',
  APP_ID: 'key_id',
  ACCOUNT_ID: 'key_id',
  APPLICATION_ID: 'key_id',
  // E17: a file-shaped credential is consumed by pointing at it, so the useful
  // thing to render into a config is the **path**, never the bytes.
  PATH: 'mount_path',
  MOUNT: 'mount_path',
  MOUNT_PATH: 'mount_path',
  FILE: 'mount_path',
};

/**
 * Entry fields no `${…}` may ever resolve to.
 *
 * Metadata, not values: `id` is the row's UUID and the other three are lists
 * that would stringify into something no config format wants. Checked before the
 * lookup, so an `extra_vars` entry keyed `id` is unreachable too — `${X/id}` has
 * to mean one thing everywhere, and making it depend on the entry's own vars is
 * the divergence this closes.
 *
 * Twin of `REFERENCE_DENY` in `envv-cli/src/refs.rs`.
 */
const REFERENCE_DENY: ReadonlySet<string> = new Set([
  'id',
  'version_history',
  'projectIds',
  'categories',
]);

/**
 * Resolve a named field from a vault entry: aliases, then the built-in field,
 * then `extra_vars`.
 *
 * The fall-through from an empty built-in to `extra_vars` matches
 * `entry_field()` in `envv-cli/src/refs.rs` — without it `${Spotify/ID}` would
 * resolve in the CLI and come back empty here for the entry that keeps its
 * client id in a var.
 */
/**
 * Normalise a role or a reference field for comparison — `account_sid`,
 * `ACCOUNT-SID` and `Account Sid` are one name. Twin: `role_key` in
 * `envv-cli/src/refs.rs`.
 */
function roleKey(raw: string): string {
  return raw.replace(/[^A-Za-z0-9]/g, '_').toUpperCase();
}

export function getEntryFieldValue(entry: VaultEntry, field: string): string | null | undefined {
  const canonical = FIELD_ALIASES[field.toUpperCase()] ?? field;
  if (REFERENCE_DENY.has(field) || REFERENCE_DENY.has(canonical)) return undefined;

  // A **declared role wins over the alias table** (Phase 23, step 2). An entry
  // whose `primary_role` is `id` holds a client id in `api_key`, so
  // `${Spotify/ID}` must answer with that rather than with `key_id` — which is
  // what the Phase 21 alias arm resolves to when no role is declared, and what
  // it still resolves to for every entry that declares none.
  const want = roleKey(field);
  if (want && want !== 'VALUE') {
    for (const [roleField, valueField] of [
      ['primary_role', 'api_key'],
      ['secret_role', 'api_secret'],
    ] as const) {
      const declared = entry[roleField];
      if (declared && roleKey(String(declared)) === want) {
        const v = entry[valueField];
        if (v != null && v !== '') return v;
      }
    }
  }
  const builtin = (
    {
      api_key: entry.api_key,
      api_secret: entry.api_secret,
      username: entry.username,
      api_url: entry.api_url,
      key_id: entry.key_id,
      email: entry.email,
      mount_path: entry.mount_path,
    } as Record<string, string | null | undefined>
  )[canonical];
  if (builtin != null && builtin !== '') return builtin;
  return entry.extra_vars?.find((v) => v.key === field || v.key === canonical)?.value;
}

/** Whether the reference target is explicitly public; unknown values fail closed. */
export function isEntryFieldPublic(entry: VaultEntry, field: string): boolean {
  const canonical = FIELD_ALIASES[field.toUpperCase()] ?? field;
  const want = roleKey(field);
  if (want && want !== 'VALUE') {
    if (entry.primary_role && roleKey(String(entry.primary_role)) === want)
      return entry.primary_public === true;
    if (entry.secret_role && roleKey(String(entry.secret_role)) === want)
      return entry.secret_public === true;
  }
  if (canonical === 'api_key') return entry.primary_public === true;
  if (canonical === 'api_secret') return entry.secret_public === true;
  if (canonical === 'key_id') return true;
  const variable = entry.extra_vars?.find((v) => v.key === field || v.key === canonical);
  if (variable) return variable.public === true || variable.secret === false;
  return ['username', 'api_url', 'email', 'mount_path', 'expires_at'].includes(canonical);
}

/**
 * Find the entry a bare `${NAME}` or a `${NAME/field}` prefix addresses.
 *
 * Three attempts, in this order, and **ambiguity is refused rather than guessed**
 * (E9):
 *
 * 1. An exact provider match, which is what a reference written by hand means.
 * 2. A **generated-name** match — the Phase 23 template. `${SPOTIFY_V2}` names
 *    the entry whose version is 2, which is the whole point of putting versions
 *    and labels into the name.
 * 3. The legacy `Provider_keyid` split on the last underscore.
 *
 * 2 and 3 occupy the same syntactic position, so a vault holding both a
 * `SPOTIFY` entry with `key_id: V2` *and* a `SPOTIFY` entry with `version: 2`
 * has two honest answers for `${SPOTIFY_V2}`. Returning either would be a
 * silent wrong value written into a config — the defect class Phase 21 was
 * about — so this returns nothing and every exporter reports it unresolved.
 * The explicit `${Provider/field}` form is never ambiguous and is what the docs
 * recommend.
 *
 * Twin: `find_entry` in `envv-cli/src/refs.rs`, pinned by the `reference_lookup`
 * section of `tests/fixtures/parity/env-names.json`.
 */
export function findEntryByRef(name: string): VaultEntry | undefined {
  const all = st.vault?.api_keys ?? [];
  const exact = all.find((e) => e.provider === name);
  if (exact) return exact;

  const want = name.toUpperCase();
  const byTemplate = all.filter(
    (e) => envName(e).toUpperCase() === want || primaryEnvName(e).toUpperCase() === want,
  );
  if (byTemplate.length > 1) return undefined;

  let legacy: VaultEntry | undefined;
  const lastUs = name.lastIndexOf('_');
  if (lastUs > 0) {
    const prov = name.slice(0, lastUs);
    const kid = name.slice(lastUs + 1);
    legacy = all.find((e) => e.provider === prov && e.key_id === kid);
  }

  if (byTemplate.length === 1) {
    return legacy && legacy !== byTemplate[0] ? undefined : byTemplate[0];
  }
  return legacy;
}

/**
 * `${bundle:Name}`, `${bundle:Name/slot}`, `${bundle:Name/slot/field}` and
 * `${bundle:Name/local}`. Twin of `resolve_bundle_ref` in `envv-cli/src/refs.rs`.
 * An ambiguous bundle name or an unknown slot is unresolved, never a guess.
 */
function resolveBundleRef(body: string, useEnvCopyField: boolean): string | null {
  const [name, second, ...rest] = body.split('/');
  const third = rest.length ? rest.join('/') : undefined;
  const bundles = st.vault.api_keys.filter(
    (e) => e.secretType === 'bundle' && e.provider.toLowerCase() === name.toLowerCase(),
  );
  if (bundles.length !== 1) return null;
  const bundle = bundles[0];
  const id = bundle.id;
  if (!id) return null;
  const member = (slot: string) =>
    st.vault.api_keys.find((e) => e.bundle_id === id && e.bundle_slot === slot);
  const primary = (e: VaultEntry): string | null => {
    const chosen = useEnvCopyField
      ? e[(Settings.get('envCopyField') || 'api_key') as keyof VaultEntry]
      : '';
    return (typeof chosen === 'string' && chosen) || e.api_key || null;
  };
  const field = (e: VaultEntry, f: string): string | null => {
    const v = getEntryFieldValue(e, f);
    return v != null && v !== '' ? String(v) : null;
  };
  if (second === undefined) {
    const pe = st.vault.api_keys.find((e) => e.id === bundle.bundle_primary);
    return pe ? primary(pe) : null;
  }
  if (third !== undefined) {
    const m = member(second);
    return m ? field(m, third) : null;
  }
  const m = member(second);
  return m ? primary(m) : field(bundle, second);
}

export function resolveFieldRef(
  value: string,
  useEnvCopyField = false,
  _depth = 0,
): {
  resolved: string | null;
  refName: string | null;
  unresolved: boolean;
  source: 'vault' | 'env_file' | 'chunk' | null;
} {
  const match = /^\$\{(.+)}$/.exec(value);
  if (!match) return { resolved: value, refName: null, unresolved: false, source: null };
  const refName = match[1];

  if (refName.startsWith('bundle:')) {
    const resolved = resolveBundleRef(refName.slice(7), useEnvCopyField);
    return {
      resolved,
      refName,
      unresolved: resolved == null,
      source: resolved == null ? null : 'vault',
    };
  }

  // Cross-chunk notation: ${chunk:ChunkName/FieldKey} — resolve any chunk field across all projects.
  // Recursively resolves if the target is itself a ${ref} (depth-guarded against cycles).
  if (refName.startsWith('chunk:')) {
    const body = refName.slice(6);
    const slash = body.indexOf('/');
    if (slash < 0) return { resolved: null, refName, unresolved: true, source: null };
    const chunkName = body.slice(0, slash);
    const fieldKey = body.slice(slash + 1);
    for (const project of st.vault.projects) {
      for (const chunk of project.chunks || []) {
        if (chunk.name !== chunkName) continue;
        const f = chunk.fields.find((ff) => ff.key === fieldKey);
        if (!f) continue;
        if (_depth < 4 && /^\$\{.+}$/.test(f.value)) {
          const nested = resolveFieldRef(f.value, useEnvCopyField, _depth + 1);
          return {
            resolved: nested.resolved,
            refName,
            unresolved: nested.unresolved,
            source: nested.source ?? 'chunk',
          };
        }
        return { resolved: f.value, refName, unresolved: false, source: 'chunk' };
      }
    }
    return { resolved: null, refName, unresolved: true, source: null };
  }

  // Slash notation: ${PROVIDER/field} or ${PROVIDER_LABEL/field} — direct field access.
  const slashIdx = refName.indexOf('/');
  if (slashIdx >= 0) {
    const provPart = refName.slice(0, slashIdx);
    const field = refName.slice(slashIdx + 1);
    const entry = findEntryByRef(provPart);
    if (entry) {
      const val = getEntryFieldValue(entry, field);
      const resolved = val != null && val !== '' ? String(val) : null;
      return { resolved, refName, unresolved: !resolved, source: 'vault' };
    }
    return { resolved: null, refName, unresolved: true, source: null };
  }

  const entry = findEntryByRef(refName);
  if (entry) {
    let resolved: string | null;
    if (useEnvCopyField) {
      const fieldName = (Settings.get('envCopyField') || 'api_key') as keyof VaultEntry;
      const rawVal = entry[fieldName];
      resolved =
        typeof rawVal === 'string' || typeof rawVal === 'number'
          ? String(rawVal) || entry.api_key || null
          : entry.api_key || null;
    } else {
      resolved = entry.api_key || null;
    }
    return { resolved, refName, unresolved: false, source: 'vault' };
  }

  for (const project of st.vault.projects) {
    for (const chunk of project.chunks || []) {
      if (chunk.chunk_type !== 'env_file') continue;
      const field = chunk.fields.find((f) => f.key === refName);
      if (field) return { resolved: field.value, refName, unresolved: false, source: 'env_file' };
    }
  }
  return { resolved: null, refName, unresolved: true, source: null };
}

// ── Field copy text formatter ──────────────────────────────────────────────

/** Returns the field formatted in its native config syntax for clipboard. */
/**
 * Rewrites every `${PROVIDER…}` chunk reference after an entry is renamed.
 *
 * References resolve by provider name (see {@link resolveFieldRef}), so
 * renaming an entry used to break every chunk field pointing at it — silently,
 * with the field simply starting to render unresolved. The security audit could
 * already *detect* the resulting stale refs; nothing prevented them. Projects
 * and categories cascade their renames, and this brings entries in line.
 *
 * Handles all four reference spellings: `${Provider}`, `${Provider/field}`,
 * `${Provider_KeyId}` and `${Provider_KeyId/field}`. Leaves `${chunk:…}` alone —
 * those address a chunk, not an entry.
 *
 * @returns how many fields were rewritten.
 */
export function renameProviderRefs(
  oldProvider: string,
  oldKeyId: string | null | undefined,
  newProvider: string,
  newKeyId: string | null | undefined,
): number {
  const oldNames = new Set<string>([oldProvider]);
  if (oldKeyId) oldNames.add(`${oldProvider}_${oldKeyId}`);
  const newCompound = newKeyId ? `${newProvider}_${newKeyId}` : newProvider;

  let changed = 0;
  for (const project of st.vault.projects) {
    for (const chunk of project.chunks || []) {
      for (const field of chunk.fields || []) {
        const match = typeof field.value === 'string' && /^\$\{(.+)}$/.exec(field.value);
        if (!match) continue;
        const body = match[1];
        if (body.startsWith('chunk:') || body.startsWith('bundle:')) continue;

        const slash = body.indexOf('/');
        const head = slash >= 0 ? body.slice(0, slash) : body;
        if (!oldNames.has(head)) continue;

        // A bare `${Provider}` becomes the new compound name; a `${x/field}`
        // keeps its field suffix.
        const replacement =
          head === oldProvider && slash < 0 && !oldKeyId ? newProvider : newCompound;
        field.value = slash >= 0 ? `\${${replacement}${body.slice(slash)}}` : `\${${replacement}}`;
        changed++;
      }
    }
  }
  return changed;
}

function chunkFieldCopyText(key: string, value: string, chunkType: string): string {
  if (chunkType === 'env_file') return `${key}=${value}`;
  if (chunkType === 'wg_interface' || chunkType === 'wg_peer') return `${key} = ${value}`;
  if (chunkType === 'ssh_host') return `    ${key} ${value}`;
  if (chunkType.startsWith('nginx_')) return `${key} ${value};`;
  if (chunkType.startsWith('k8s_') || chunkType.startsWith('traefik_')) return `${key}: ${value}`;
  return `${key} = ${value}`;
}

