/**
 * The chunks an export should actually emit.
 *
 * `disabled` is documented as "excluded from exports", and the later exporters
 * (apache, haproxy, ansible, postgres) each check it inline. The four that
 * people actually deploy — WireGuard, Compose, nginx, k8s — did not, so
 * disabling a peer or a service in the UI greyed the card out and then shipped
 * it anyway. Disabling a WireGuard peer and still writing it into wg0.conf means
 * the tunnel keeps trusting a peer the user believes they removed.
 */
export function activeChunks(project: Project): SecretChunk[] {
  return (project.chunks || []).filter((c) => !c.disabled);
}

/**
 * Resolve a `${ref}` for an exporter, falling back to the literal on failure.
 *
 * Six of the seven experimental exporters interpolated `f.value` raw, so a
 * `${Provider/field}` reached the generated config as literal text: a `.pgpass`
 * line whose password is the string `${DB/password}`, an Apache `SSLCertificateFile`
 * pointing at nothing. That is invariant 5, and it is the *same* bug that was
 * found in `exportNginx` during Phase 13 — found there by a golden fixture,
 * missed here because these types had no fixture.
 *
 * `true` selects the env-copy field, matching every other exporter that
 * materialises a real config file.
 */
function xv(value: string | undefined | null): string {
  const v = value ?? '';
  if (!v) return '';
  return resolveFieldRef(v, true).resolved ?? v;
}

export function exportApache(project: Project): string {
  const chunks = project.chunks || [];
  const lines: string[] = ['# Generated by UnENVerse', ''];
  for (const chunk of chunks) {
    if (chunk.disabled) continue;
    if (chunk.chunk_type === 'apache_vhost') {
      const port = chunk.fields.find((f) => f.key === 'SSLEngine') ? '443' : '80';
      lines.push(`<VirtualHost *:${port}>`);
      for (const f of chunk.fields) {
        if (f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
      }
      lines.push('</VirtualHost>', '');
    } else if (chunk.chunk_type === 'apache_directory') {
      const path = xv(chunk.fields.find((f) => f.key === 'path')?.value) || '/';
      lines.push(`<Directory ${path}>`);
      for (const f of chunk.fields) {
        if (f.key !== 'path' && f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
      }
      lines.push('</Directory>', '');
    }
  }
  return lines.join('\n');
}

export function exportHaproxy(project: Project): string {
  const chunks = project.chunks || [];
  const lines: string[] = ['# Generated by UnENVerse', ''];
  for (const chunk of chunks) {
    if (chunk.disabled) continue;
    if (chunk.chunk_type === 'haproxy_global') {
      lines.push('global');
      for (const f of chunk.fields) {
        if (f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
      }
      lines.push('');
    } else if (chunk.chunk_type === 'haproxy_frontend') {
      lines.push(`frontend ${chunk.name}`);
      for (const f of chunk.fields) {
        if (f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
      }
      lines.push('');
    } else if (chunk.chunk_type === 'haproxy_backend') {
      lines.push(`backend ${chunk.name}`);
      for (const f of chunk.fields) {
        if (f.value) lines.push(`    ${f.key} ${xv(f.value)}`);
      }
      lines.push('');
    }
  }
  return lines.join('\n');
}

export function exportAnsible(project: Project): string {
  const chunks = project.chunks || [];
  const varChunks = chunks.filter((c) => !c.disabled && c.chunk_type === 'ansible_vars');
  const taskChunks = chunks.filter((c) => !c.disabled && c.chunk_type === 'ansible_task');

  const varLines = (indent: string) => {
    const out: string[] = [];
    for (const chunk of varChunks) {
      out.push(`${indent}# ${chunk.name}`);
      for (const f of chunk.fields) {
        if (f.key) out.push(`${indent}${f.key}: ${JSON.stringify(xv(f.value))}`);
      }
    }
    return out;
  };

  const taskLines = (indent: string) => {
    const out: string[] = [];
    for (const chunk of taskChunks) {
      const name = xv(chunk.fields.find((f) => f.key === 'name')?.value) || chunk.name;
      const module = xv(chunk.fields.find((f) => f.key === 'module')?.value) || 'debug';
      out.push(`${indent}- name: ${name}`, `${indent}  ${module}:`);
      for (const f of chunk.fields) {
        if (f.key !== 'name' && f.key !== 'module' && f.key)
          out.push(`${indent}    ${f.key}: ${JSON.stringify(xv(f.value))}`);
      }
    }
    return out;
  };

  // Emitting vars and tasks into one document produced a mapping immediately
  // followed by a sequence, which is not valid YAML in any parser — so the
  // output was unusable by the tool it targets, and nothing noticed because
  // nothing had ever run `ansible-playbook` against it. Found by the Phase 18
  // validation matrix.
  //
  // The shape now follows how Ansible actually consumes these files:
  //   tasks present → a playbook (one play, with vars folded into it)
  //   vars only     → a bare mapping, which is what group_vars/host_vars want
  if (taskChunks.length) {
    const lines = ['# Generated by UnENVerse', '- hosts: all'];
    if (varChunks.length) {
      lines.push('  vars:');
      lines.push(...varLines('    '));
    }
    lines.push('  tasks:');
    lines.push(...taskLines('    '));
    return lines.join('\n');
  }

  const lines = ['# Generated by UnENVerse'];
  if (varChunks.length) lines.push(...varLines(''));
  return lines.join('\n');
}

export function exportPostgres(project: Project): string {
  const chunks = project.chunks || [];
  const lines: string[] = [
    '# Generated by UnENVerse — .pgpass format: host:port:dbname:user:password',
  ];
  for (const chunk of chunks) {
    if (chunk.disabled) continue;
    if (chunk.chunk_type === 'pg_connection') {
      const g = (k: string) => xv(chunk.fields.find((f) => f.key === k)?.value);
      lines.push(
        `${g('host')}:${g('port') || '5432'}:${g('dbname')}:${g('user')}:${g('password')}`,
      );
    }
  }
  return lines.join('\n');
}

