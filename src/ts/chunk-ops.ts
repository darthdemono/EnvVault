// ── Chunk → string (copy-chunk-full) ──────────────────────────────────────

function serviceChunkToYaml(sc: SecretChunk): string {
  const yamlStr = (v: string): string => {
    if (!v) return '""';
    if (/[\s:#\[\]{},|>&*!'"@`]/.test(v)) return JSON.stringify(v);
    return v;
  };
  const quoteItem = (v: string): string => (/\s/.test(v) ? JSON.stringify(v) : v);
  const svcName = sc.name.replace(/\s+/g, '_').toLowerCase();
  const out: string[] = [`${svcName}:`];

  const envFields: ChunkField[] = [];
  const portItems: string[] = [];
  const volumeItems: string[] = [];
  const listMap = new Map<string, string[]>();
  const scalars: [string, string][] = [];

  for (const f of sc.fields) {
    if (!f.key || f.key === 'restart') continue;
    if (f.description === 'env' || f.field_type === 'env_var') {
      envFields.push(f);
    } else if (f.key === 'ports' || f.field_type === 'port') {
      portItems.push(
        ...f.value
          .split(/[\n,]+/)
          .map((s) => s.trim())
          .filter(Boolean),
      );
    } else if (f.key === 'volumes' || f.field_type === 'volume_mount') {
      volumeItems.push(
        ...f.value
          .split(/\n/)
          .map((s) => s.trim())
          .filter(Boolean),
      );
    } else if (f.key === 'networks' || f.key === 'depends_on' || f.field_type === 'list') {
      if (!listMap.has(f.key)) listMap.set(f.key, []);
      listMap.get(f.key)!.push(
        ...f.value
          .split(/[\n,]+/)
          .map((s) => s.trim())
          .filter(Boolean),
      );
    } else if (f.value != null && f.value !== '') {
      scalars.push([f.key, f.value]);
    }
  }

  const PRIO = [
    'image',
    'container_name',
    'user',
    'hostname',
    'network_mode',
    'pid',
    'entrypoint',
    'command',
  ];
  const scalarMap = new Map(scalars);
  for (const k of PRIO) {
    if (scalarMap.has(k)) {
      out.push(`  ${k}: ${yamlStr(scalarMap.get(k)!)}`);
      scalarMap.delete(k);
    }
  }
  for (const [k, v] of scalarMap) out.push(`  ${k}: ${yamlStr(v)}`);

  if (portItems.length) {
    out.push('  ports:');
    for (const p of portItems) out.push(`    - ${JSON.stringify(p)}`);
  }
  if (envFields.length) {
    out.push('  environment:');
    for (const f of envFields) {
      const ref = f.ref_name || (/^\$\{(.+)}$/.exec(f.value) || [])[1];
      out.push(`    - ${f.key}=${ref ? `\${${ref}}` : (f.value ?? '')}`);
    }
  }
  if (volumeItems.length) {
    out.push('  volumes:');
    for (const v of volumeItems) out.push(`    - ${quoteItem(v)}`);
  }
  for (const [k, items] of listMap) {
    out.push(`  ${k}:`);
    for (const item of items) out.push(`    - ${yamlStr(item)}`);
  }
  const restartF = sc.fields.find((f) => f.key === 'restart');
  out.push(`  restart: ${restartF?.value || 'unless-stopped'}`);
  return out.join('\n');
}

/** Format a single chunk as its native config text for clipboard copy. */
export function chunkToString(chunk: SecretChunk): string {
  const isWg = chunk.chunk_type === 'wg_interface' || chunk.chunk_type === 'wg_peer';
  const isEnv = chunk.chunk_type === 'env_file';
  const isNginxBlock = ['nginx_server', 'nginx_location', 'nginx_upstream'].includes(
    chunk.chunk_type,
  );
  if (chunk.chunk_type === 'nginx_key') {
    return chunk.fields.find((f) => f.key === 'content')?.value ?? '';
  }
  const isTraefik = ['traefik_router', 'traefik_service', 'traefik_middleware'].includes(
    chunk.chunk_type,
  );
  const isK8s = ['k8s_deployment', 'k8s_service', 'k8s_ingress', 'k8s_configmap'].includes(
    chunk.chunk_type,
  );
  const isSsh = chunk.chunk_type === 'ssh_host';

  if (isWg) {
    const header = chunk.chunk_type === 'wg_interface' ? '[Interface]' : '[Peer]';
    const lines = [header];
    for (const f of chunk.fields) {
      // Resolve, like the env_file branch below and like exportWireGuard. The
      // old comment here said the caller would decide, but the only caller is
      // copy-to-clipboard and it does not resolve — so copying an Interface
      // pasted `PrivateKey = ${MyKey}` into wg0.conf and the tunnel would not
      // come up. A copied config has to be deployable.
      lines.push(`${f.key} = ${resolveFieldRef(f.value ?? '', true).resolved ?? f.value ?? ''}`);
    }
    return lines.join('\n');
  }

  if (isEnv) {
    // Resolve ${ref} values to actual secrets — a copied .env must be deployable.
    return chunk.fields
      .filter((f) => f.key)
      .map((f) => `${f.key}=${resolveFieldRef(f.value ?? '', true).resolved ?? f.value ?? ''}`)
      .join('\n');
  }

  if (isNginxBlock) {
    // `upstream` was folded in with `server`, so copying an upstream chunk
    // produced `server { server 10.0.0.1; }` — the wrong directive, with the
    // upstream's name dropped, which nginx rejects. exportNginx has always got
    // this right; the two disagreed.
    const blockType =
      chunk.chunk_type === 'nginx_location'
        ? 'location'
        : chunk.chunk_type === 'nginx_upstream'
          ? 'upstream'
          : 'server';
    const pathField = chunk.fields.find((f) => f.key === 'path');
    const blockName =
      chunk.chunk_type === 'nginx_location'
        ? pathField?.value
          ? ` ${pathField.value}`
          : ''
        : chunk.chunk_type === 'nginx_upstream'
          ? chunk.name
            ? ` ${chunk.name}`
            : ''
          : ''; // server block has no inline name
    const inner = chunk.fields
      .filter((f) => f.key && f.key !== 'path' && f.value)
      .map((f) => `    ${f.key} ${resolveFieldRef(f.value, true).resolved ?? f.value};`)
      .join('\n');
    return `${blockType}${blockName} {\n${inner}\n}`;
  }

  if (isSsh) {
    const lines = [`Host ${chunk.name}`];
    for (const f of chunk.fields) {
      if (f.key && f.value)
        lines.push(`    ${f.key} ${resolveFieldRef(f.value, true).resolved ?? f.value}`);
    }
    return lines.join('\n');
  }

  if (isTraefik || isK8s) {
    // YAML-like key: value
    return chunk.fields
      .filter((f) => f.key)
      .map((f) => `${f.key}: ${f.value ?? ''}`)
      .join('\n');
  }

  if (chunk.chunk_type === 'docker_service') {
    return serviceChunkToYaml(chunk);
  }

  // Generic unknown: key: value
  return chunk.fields
    .filter((f) => f.key)
    .map((f) => `${f.key}: ${f.value ?? ''}`)
    .join('\n');
}

// ── Export functions ───────────────────────────────────────────────────────

export function exportWireGuard(project: Project): string {
  const chunks = activeChunks(project);
  const sections: string[] = [];
  for (const chunk of chunks) {
    const header =
      chunk.chunk_type === 'wg_interface'
        ? '[Interface]'
        : chunk.chunk_type === 'wg_peer'
          ? '[Peer]'
          : `# ${chunk.name}`;
    const lines = [header];
    for (const field of chunk.fields) {
      if (!field.value) continue;
      // Use the shared resolver rather than matching `${PROVIDER}` by hand.
      // The hand-rolled version understood only the bare legacy form, so
      // `${Provider/field}`, `${Provider_KeyId}`, `${chunk:…}` and .env-backed
      // references were all written out as literal `${…}` text — producing a
      // wg0.conf with a placeholder where the private key should be, which
      // WireGuard then rejects.
      const { resolved } = resolveFieldRef(field.value, true);
      lines.push(`${field.key} = ${resolved ?? field.value}`);
    }
    sections.push(lines.join('\n'));
  }
  return sections.join('\n\n');
}

export function exportDockerCompose(project: Project): { yaml: string; envFile: string } {
  const chunks = activeChunks(project);
  const serviceChunks = chunks.filter((c) => c.chunk_type === 'docker_service');
  const networkChunks = chunks.filter((c) => c.chunk_type === 'docker_network');
  const volumeChunks = chunks.filter((c) => c.chunk_type === 'docker_volume');

  const out: string[] = ['# Generated by EnvVault', ''];
  const envLines: string[] = [];

  const yamlStr = (v: string): string => {
    if (!v) return '""';
    if (/[\s:#\[\]{},|>&*!'"@`]/.test(v)) return JSON.stringify(v);
    return v;
  };
  const quoteItem = (v: string): string => (/\s/.test(v) ? JSON.stringify(v) : v);

  if (networkChunks.length) {
    out.push('networks:');
    for (const nc of networkChunks) {
      for (const f of nc.fields) {
        if (!f.key) continue;
        out.push(`  ${f.key}:`);
        if (f.value) out.push(`    driver: ${f.value}`);
      }
      if (!nc.fields.length) out.push(`  ${nc.name}:`);
    }
    out.push('');
  }

  if (volumeChunks.length) {
    out.push('volumes:');
    for (const vc of volumeChunks) {
      for (const f of vc.fields) {
        if (f.key) out.push(`  ${f.key}:`);
      }
      if (!vc.fields.length) out.push(`  ${vc.name}:`);
    }
    out.push('');
  }

  if (serviceChunks.length) {
    out.push('services:');
    for (const sc of serviceChunks) {
      const svcName = sc.name.replace(/\s+/g, '_').toLowerCase();
      out.push(`  ${svcName}:`);

      const envFields: ChunkField[] = [];
      const portItems: string[] = [];
      const volumeItems: string[] = [];
      const listMap = new Map<string, string[]>();
      const scalars: [string, string][] = [];

      for (const f of sc.fields) {
        if (!f.key || f.key === 'restart') continue;
        if (f.description === 'env' || f.field_type === 'env_var') {
          envFields.push(f);
        } else if (f.key === 'ports' || f.field_type === 'port') {
          portItems.push(
            ...f.value
              .split(/[\n,]+/)
              .map((s) => s.trim())
              .filter(Boolean),
          );
        } else if (f.key === 'volumes' || f.field_type === 'volume_mount') {
          volumeItems.push(
            ...f.value
              .split(/\n/)
              .map((s) => s.trim())
              .filter(Boolean),
          );
        } else if (f.key === 'networks' || f.key === 'depends_on' || f.field_type === 'list') {
          const key = f.key;
          if (!listMap.has(key)) listMap.set(key, []);
          listMap.get(key)!.push(
            ...f.value
              .split(/[\n,]+/)
              .map((s) => s.trim())
              .filter(Boolean),
          );
        } else if (f.value != null && f.value !== '') {
          scalars.push([f.key, f.value]);
        }
      }

      // Scalars — priority order
      const PRIO = [
        'image',
        'container_name',
        'user',
        'hostname',
        'network_mode',
        'pid',
        'entrypoint',
        'command',
      ];
      const scalarMap = new Map(scalars);
      for (const k of PRIO) {
        if (scalarMap.has(k)) {
          out.push(`    ${k}: ${yamlStr(scalarMap.get(k)!)}`);
          scalarMap.delete(k);
        }
      }
      for (const [k, v] of scalarMap) out.push(`    ${k}: ${yamlStr(v)}`);

      // Ports
      if (portItems.length) {
        out.push('    ports:');
        for (const p of portItems) out.push(`      - ${JSON.stringify(p)}`);
      }

      // Environment: - KEY=value format
      if (envFields.length) {
        out.push('    environment:');
        for (const f of envFields) {
          const ref = f.ref_name || (/^\$\{(.+)}$/.exec(f.value) || [])[1];
          if (ref) {
            // Compose substitutes ${NAME} from the .env beside it, and NAME has
            // to be a valid shell identifier — a reference like `Provider/field`
            // is not one, so derive the variable name from the field key.
            const varName = f.key.toUpperCase().replace(/[^A-Z0-9_]/g, '_');
            out.push(`      - ${f.key}=\${${varName}}`);
            // Resolve through the shared resolver: matching provider names by
            // hand only understood the bare `${PROVIDER}` form, so every other
            // reference shape wrote an empty value into the .env file and the
            // container started with a blank secret.
            const { resolved } = resolveFieldRef(f.value ?? '', true);
            envLines.push(`${varName}=${resolved ?? ''}`);
          } else {
            out.push(`      - ${f.key}=${f.value ?? ''}`);
          }
        }
      }

      // Volumes
      if (volumeItems.length) {
        out.push('    volumes:');
        for (const v of volumeItems) out.push(`      - ${quoteItem(v)}`);
      }

      // Networks, depends_on, and other lists
      for (const [k, items] of listMap) {
        out.push(`    ${k}:`);
        for (const item of items) out.push(`      - ${yamlStr(item)}`);
      }

      // Restart
      const restartF = sc.fields.find((f) => f.key === 'restart');
      out.push(`    restart: ${restartF?.value || 'unless-stopped'}`);
      out.push('');
    }
  }

  return { yaml: out.join('\n'), envFile: envLines.join('\n') };
}

export function exportServicesSection(project: Project): string {
  const svcChunks = activeChunks(project).filter((c) => c.chunk_type === 'docker_service');
  if (!svcChunks.length) return '';
  const lines = ['services:'];
  for (const sc of svcChunks) {
    serviceChunkToYaml(sc)
      .split('\n')
      .forEach((l) => lines.push('  ' + l));
    lines.push('');
  }
  return lines.join('\n');
}

