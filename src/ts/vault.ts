/**
 * The dynamic file picker, hoisted so `finishInit` can hand it to the onboarding
 * wizard. It is created inside `init()` because it closes over nothing else —
 * see the WebKitGTK ghost-widget note there.
 */
let _openFilePicker: ((accept: string) => void) | null = null;

async function finishInit() {
  // See `html.booting` in base.css: the shell paints only once boot knows
  // whether a lock screen is going up in front of it.
  document.documentElement.classList.remove('booting');
  try {
    const r = await fetch('./schema.json');
    if (r.ok) st.schema = (await r.json()) as typeof st.schema;
  } catch {}

  try {
    const data = await st.store.load();
    if (data) {
      const remoteEmpty = !data.api_keys?.length;
      const localHasData = st.vault.api_keys.length > 0;

      // Remote vault empty but in-memory vault has data: offer to push before overwriting.
      if (remoteEmpty && localHasData && st.store.isRemote) {
        const push = await showConfirm(
          `Remote vault is empty — push your ${st.vault.api_keys.length} local entries to it?`,
        );
        if (push) {
          await persist();
          showToast(`Pushed ${st.vault.api_keys.length} entries to remote ✓`, 'ok', 2500);
          // Keep existing st.vault — do not overwrite with empty remote data.
        } else {
          st.vault.api_keys = [];
          st.vault.user_categories = [];
          st.vault.projects = [{ id: 'Universal', name: 'Universal', description: '' }];
        }
      } else {
        // `|| []` on all three: a vault blob written by an older build (or an
        // edited backup) can be missing a key entirely, and an undefined
        // api_keys threw on the very next line that iterates it.
        st.vault.api_keys = data.api_keys || [];
        st.vault.user_categories = data.user_categories || [];
        st.vault.projects = data.projects || [
          { id: 'Universal', name: 'Universal', description: '' },
        ];
      }

      if (!st.vault.projects.find((p) => p.id === 'Universal')) {
        st.vault.projects.unshift({ id: 'Universal', name: 'Universal', description: '' });
      }

      let needsSave = false;
      for (const key of st.vault.api_keys) {
        if (!key.projectIds) {
          key.projectIds = ['Universal'];
          needsSave = true;
        } else if (!key.projectIds.includes('Universal')) {
          key.projectIds.push('Universal');
          needsSave = true;
        }
        if (!key.secretType) {
          key.secretType = 'api_key';
          needsSave = true;
        }
        // The 'chunk' secret type has been removed — it could never be saved
        // through the UI anyway (its key field was hidden but still required).
        // Its content lived in extra_vars, which the normal card renders too, so
        // relabelling loses nothing.
        if ((key.secretType as string) === 'chunk') {
          key.secretType = 'env_var';
          needsSave = true;
        }
      }
      // Backfill stable ids for vaults written before the field existed, and
      // repair any duplicates. Runs once; afterwards every entry carries an id.
      if (ensureEntryIds(st.vault.api_keys)) needsSave = true;

      // Creation dates, from the audit log's `add` rows. Wrapped because the
      // audit read can fail in ways that must not stop a vault opening: a
      // scoped sub-user gets 403 from `/api/audit`, and a vault restored
      // without its audit table has no rows at all. Either way the entries
      // simply stay undated.
      if (st.vault.api_keys.some((e) => !e.created_at)) {
        try {
          const { loadAuditRows } = await import('./audit');
          const rows = await loadAuditRows();
          if (backfillCreatedAt(st.vault.api_keys, rows)) needsSave = true;
        } catch {}
      }

      if (needsSave) await persist();

      document.getElementById('load-banner')!.style.display = 'none';
      st.vaultOpen = true;
      // From here the vault can also be written from outside this window — a
      // terminal running `envv`, or a LAN peer. Idempotent by assignment, so
      // re-unlocking leaves one timer.
      startVaultWatch();
      showToast(`Loaded ${st.vault.api_keys.length} keys`, 'ok', 1800);
    } else {
      document.getElementById('load-banner')!.style.display = 'flex';
    }
  } catch {
    document.getElementById('load-banner')!.style.display = 'flex';
  }

  // Restore the last grid view *before* the first render, so the app paints once
  // in its final state instead of flashing the unfiltered grid. restoreViewState
  // drops any id the loaded vault does not have — see its doc comment.
  restoreViewState();

  render();
  resetLock();
  initTools();
  initUsersPanel();
  initAuthPanel();
  applyUsersPanelVisibility();
  initRemotePanel();
  initLanPanel();
  setRemoteFinishInitFn(finishInit);

  // First-run wizard, last so it opens over a fully painted app rather than a
  // half-built one. Local vaults only: connecting to a remote is not a first
  // run, and the wizard writes local display settings that have nothing to do
  // with the server you just reached.
  if (!st.store.isRemote && st.vaultOpen && shouldShowOnboarding()) {
    showOnboarding({
      onAdd: () => openAdd(),
      onImport: () => _openFilePicker?.('.json,.env,text/plain'),
    });
  }
}

