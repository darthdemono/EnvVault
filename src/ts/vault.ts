/** Grid sort modes. Module-level so the persisted value can be validated against it. */
const SORT_OPTIONS = [
  { value: 'provider', label: 'A – Z' },
  { value: 'price', label: 'Price Type' },
  { value: 'category', label: 'Category' },
  { value: 'expiry', label: 'Expiry' },
];

/**
 * Applies the persisted sort mode and syncs the toolbar label to it.
 *
 * The stored value is checked against SORT_OPTIONS rather than trusted: an
 * unrecognised mode falls through every branch of `sorted()` and leaves the
 * grid in insertion order while the button claims otherwise.
 */

function restoreSort(): void {
  const saved = Settings.get('lastSortBy');
  const opt = SORT_OPTIONS.find((o) => o.value === saved);
  if (!opt) return;
  st.currentSortBy = opt.value;
  const labelEl = document.getElementById('sort-label-text');
  if (labelEl) labelEl.textContent = opt.label;
}

/**
 * Copy the authenticator code shown at `el`'s slot.
 *
 * Reads the code the ticker last painted (`data-totp-code` on the
 * `[data-totp-for]` container) rather than re-deriving it, so what lands on the
 * clipboard is what the user was looking at. Re-deriving would hand them the
 * *next* code if the click crossed a step boundary — the one failure that is
 * both invisible and guaranteed to be blamed on the website.
 */
function copyTotpFrom(el: HTMLElement): void {
  const slot = el.closest<HTMLElement>('[data-totp-for]');
  const code = slot?.dataset.totpCode ?? '';
  if (!code) {
    showToast(
      inTauri ? 'No code yet — try again in a moment' : 'Codes are generated by the desktop app',
      'err',
      2000,
    );
    return;
  }
  void clipboardWrite(code);
  showToast('Code copied ✓', 'ok', 1500);
}

/**
 * The pool card's Copy button — advances the pool cursor and copies whatever
 * it landed on, exactly `envv pool next`. Members are read from the **live**
 * vault via `poolsOf`, not a snapshot the card was built with, so a member
 * deleted between render and click cannot be copied.
 */
async function copyPoolNext(poolName: string): Promise<void> {
  if (!poolName) return;
  const members = poolsOf(st.vault).get(poolName) ?? [];
  if (!members.length) return;
  const chosen = await poolNext(poolName, members);
  if (!chosen) {
    showToast(
      inTauri
        ? `Every key in "${poolName}" is rate limited`
        : 'Pool cursors are read by the desktop app',
      'err',
      2500,
    );
    return;
  }
  const realIdx = st.vault.api_keys.indexOf(chosen);
  if (realIdx < 0) return;
  doCopyEnv({ stopPropagation() {} } as Event, realIdx);
  // The badge's ready/cooling split just changed; the copied member's card
  // (if the pool is expanded) may need its own use-count refreshed too.
  triggerRender();
}

